// bun lab/sofa/export.ts <saved.json> — writes the Fire TV banner + launcher foreground from a saved lab config
import { bannerShapes, iconShapes, pathData, type Config, type Shape } from './render'

const cfg: Config = await Bun.file(process.argv[2]).json()
const res = new URL('../../firetv/app/src/main/res/drawable/', import.meta.url).pathname
const GROUND = { ink: '#FF12161C', navy: '#FF0E1A33', glow: '#FF12161C' }[cfg.ground]
const argb = (c: string) => '#FF' + c.slice(1).toUpperCase()

const path = (s: Shape) =>
  s.fill
    ? `    <path android:fillColor="${argb(s.fill)}" android:pathData="${pathData(s)}" />`
    : `    <path android:strokeColor="${argb(s.stroke!)}" android:strokeWidth="${+s.sw!.toFixed(2)}" android:strokeLineCap="${s.cap}" android:strokeLineJoin="round" android:pathData="${pathData(s)}" />`

const vector = (comment: string, w: number, h: number, body: string[]) => `<?xml version="1.0" encoding="utf-8"?>
<!-- ${comment}
     Generated by lab/sofa/export.ts from lab/sofa/saved (seed ${cfg.seed}); regenerate rather than hand-edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="${w}dp"
    android:height="${h}dp"
    android:viewportWidth="${w}"
    android:viewportHeight="${h}">
${body.join('\n')}
</vector>
`

await Bun.write(res + 'banner.xml', vector(
  '320x180 TV launcher banner: the Sofa mark (a front-view sofa with a live dot) and the "sofa" wordmark on ink.',
  320, 180, [`    <path android:fillColor="${GROUND}" android:pathData="M0,0h320v180h-320z" />`, ...bannerShapes(cfg).map(path)],
))
await Bun.write(res + 'ic_launcher_foreground.xml', vector(
  'Adaptive launcher foreground: the Sofa mark, on @color/icon_background.',
  108, 108, iconShapes(cfg).map(path),
))
console.log('wrote banner.xml + ic_launcher_foreground.xml')
